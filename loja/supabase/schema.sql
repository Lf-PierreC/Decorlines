-- 9. PERMISSÕES PARA O SERVIDOR NEXT.JS E BUCKET DE IMAGENS
-- Como toda a segurança (login, sessão HTTP-only e verificação de admin) roda
-- dentro do servidor Next.js ("server-only"), liberamos o acesso da API às tabelas:
ALTER TABLE public.users DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.sessions DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.products DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.addresses DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.cards DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders DISABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.users, public.sessions, public.products, public.addresses, public.cards, public.orders TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- Políticas para permitir upload e leitura pública das fotos no bucket 'produtos'
DROP POLICY IF EXISTS "Leitura publica fotos produtos" ON storage.objects;
CREATE POLICY "Leitura publica fotos produtos"
ON storage.objects FOR SELECT
USING (bucket_id = 'produtos');

DROP POLICY IF EXISTS "Upload fotos produtos" ON storage.objects;
CREATE POLICY "Upload fotos produtos"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'produtos');

