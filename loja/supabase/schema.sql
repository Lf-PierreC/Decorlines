-- 1. TABELA DE USUÁRIOS (CLIENTES E ADMINISTRADORES)
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  cpf TEXT,
  phone TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users (email);

-- Trigger automático: o 1º usuário cadastrado na loja vira 'admin' automaticamente
CREATE OR REPLACE FUNCTION public.promote_first_user_to_admin()
RETURNS TRIGGER AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.users WHERE role = 'admin') THEN
    NEW.role := 'admin';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_promote_first_user ON public.users;
CREATE TRIGGER trg_promote_first_user
BEFORE INSERT ON public.users
FOR EACH ROW
EXECUTE FUNCTION public.promote_first_user_to_admin();


-- 2. TABELA DE SESSÕES DE LOGIN (AUTENTICAÇÃO SEGURA VIA COOKIE HTTP-ONLY)
CREATE TABLE IF NOT EXISTS public.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON public.sessions (user_id);


-- 3. TABELA DE PRODUTOS (CATÁLOGO DE IMPRESSÃO 3D)
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
  tone TEXT NOT NULL DEFAULT '#e9dfd5',
  image TEXT,
  description TEXT NOT NULL DEFAULT '',
  details JSONB NOT NULL DEFAULT '[]'::jsonb,
  weight_kg NUMERIC(6, 3) NOT NULL DEFAULT 0.300,
  width_cm INTEGER NOT NULL DEFAULT 16,
  height_cm INTEGER NOT NULL DEFAULT 22,
  length_cm INTEGER NOT NULL DEFAULT 16,
  stock INTEGER NOT NULL DEFAULT 10 CHECK (stock >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_products_active_category ON public.products (active, category);


-- 4. TABELA DE MÚLTIPLOS ENDEREÇOS DO CLIENTE
CREATE TABLE IF NOT EXISTS public.addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  label TEXT NOT NULL DEFAULT 'Casa',          -- Ex: "Casa", "Trabalho", "Casa dos Pais"
  recipient TEXT NOT NULL,                     -- Nome de quem vai receber
  cep TEXT NOT NULL,                           -- 8 dígitos (ex: "08810230")
  endereco TEXT NOT NULL,                      -- Rua / Avenida
  numero TEXT NOT NULL,
  complemento TEXT NOT NULL DEFAULT '',
  bairro TEXT NOT NULL,
  cidade TEXT NOT NULL,
  uf CHAR(2) NOT NULL,
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_addresses_user_id ON public.addresses (user_id);


-- 5. TABELA DE CARTÕES SALVOS (CARTEIRA TOKENIZADA — SEM NÚMERO REAL OU CVV)
CREATE TABLE IF NOT EXISTS public.cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  label TEXT NOT NULL DEFAULT 'Cartão Principal',
  brand TEXT NOT NULL,                         -- Ex: "Mastercard", "Visa", "Elo"
  holder_name TEXT NOT NULL,                   -- Nome impresso no cartão
  last4 CHAR(4) NOT NULL,                      -- Apenas os 4 últimos dígitos
  expiry TEXT NOT NULL,                        -- MM/AA
  token TEXT NOT NULL,                         -- Token criptográfico
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_cards_user_id ON public.cards (user_id);


-- 6. TABELA DE PEDIDOS (COM FRETE MELHOR ENVIO, RASTREIO E INFINITEPAY)
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,                   -- Ex: "DL-8F4A2B"
  user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,    -- Lista de peças compradas, qtd e preço unitário
  subtotal NUMERIC(10, 2) NOT NULL,
  shipping NUMERIC(10, 2) NOT NULL,
  discount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  total NUMERIC(10, 2) NOT NULL,
  payment TEXT NOT NULL CHECK (payment IN ('pix', 'card')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'canceled')),
  tracking_code TEXT,                          -- Código de rastreio Correios / Jadlog / Melhor Envio
  customer JSONB,                              -- Snapshot do cliente, endereço de entrega e frete escolhido
  payment_meta JSONB,                          -- Dados da InfinitePay (checkoutUrl, invoiceSlug, receiptUrl, etc.)
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_orders_user_id ON public.orders (user_id);
CREATE INDEX IF NOT EXISTS idx_orders_code ON public.orders (code);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders (status);


